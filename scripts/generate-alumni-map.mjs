import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

import { geoConicEqualArea, geoPath } from "d3-geo";
import { feature } from "topojson-client";

const projectRoot = fileURLToPath(new URL("..", import.meta.url));
const sourceDirectory = `${projectRoot}/public/data`;
const outputPath = `${projectRoot}/src/features/alumni/north-america-paths.ts`;

const projection = geoConicEqualArea()
  .parallels([20, 60])
  .rotate([96, 0])
  .center([0, 40]);

const squareDistance = ([x1, y1], [x2, y2]) => {
  const deltaX = x1 - x2;
  const deltaY = y1 - y2;
  return deltaX * deltaX + deltaY * deltaY;
};

const simplifyRadialDistance = (points, squareTolerance) => {
  let previousPoint = points[0];
  const simplified = [previousPoint];

  for (let index = 1; index < points.length; index += 1) {
    const point = points[index];
    if (squareDistance(point, previousPoint) > squareTolerance) {
      simplified.push(point);
      previousPoint = point;
    }
  }

  if (previousPoint !== points.at(-1)) {
    simplified.push(points.at(-1));
  }

  return simplified;
};

const signedRingArea = (points) =>
  points.reduce((area, point, index) => {
    const nextPoint = points[(index + 1) % points.length];
    return area + point[0] * nextPoint[1] - nextPoint[0] * point[1];
  }, 0);

const simplifyLine = (points, tolerance = 0.12) => {
  if (points.length <= 4) {
    return points;
  }

  const closed = squareDistance(points[0], points.at(-1)) === 0;
  const source = closed ? points.slice(0, -1) : points;
  const squareTolerance = tolerance * tolerance;
  const radial = simplifyRadialDistance(source, squareTolerance);

  if (radial.length < (closed ? 3 : 2)) {
    return points;
  }

  if (!closed) {
    return radial;
  }

  const originalDirection = Math.sign(signedRingArea(source));
  const simplifiedDirection = Math.sign(signedRingArea(radial));

  if (simplifiedDirection === 0) {
    return points;
  }

  const correctlyWound =
    originalDirection === simplifiedDirection ? radial : [...radial].reverse();
  const simplified = [...correctlyWound, correctlyWound[0]];

  return simplified.length >= 4 ? simplified : points;
};

const simplifyGeometry = (geometry) => {
  if (!geometry) {
    return geometry;
  }

  if (geometry.type === "Polygon") {
    return {
      ...geometry,
      coordinates: geometry.coordinates.map((ring) => simplifyLine(ring)),
    };
  }

  if (geometry.type === "MultiPolygon") {
    return {
      ...geometry,
      coordinates: geometry.coordinates.map((polygon) =>
        polygon.map((ring) => simplifyLine(ring)),
      ),
    };
  }

  return geometry;
};

const roundPath = (path) =>
  path.replace(/-?\d+\.\d+/g, (number) =>
    String(Math.round(Number(number) * 10) / 10),
  );

const renderPaths = (features) =>
  features
    .map((mapFeature) => ({
      ...mapFeature,
      geometry: simplifyGeometry(mapFeature.geometry),
    }))
    .map((mapFeature) => roundPath(pathGenerator(mapFeature) ?? ""))
    .filter(Boolean);

const [usTopology, canadaGeoJson] = await Promise.all([
  readFile(`${sourceDirectory}/us-states-10m.json`, "utf8").then(JSON.parse),
  readFile(`${sourceDirectory}/canada-provinces.geojson`, "utf8").then(JSON.parse),
]);

const excludedStateIds = new Set(["02", "15", "60", "66", "69", "72", "78"]);
const usStates = feature(usTopology, usTopology.objects.states).features.filter(
  (state) => !excludedStateIds.has(String(state.id).padStart(2, "0")),
);
const mapFeatures = [...usStates, ...canadaGeoJson.features];
projection.fitExtent(
  [
    [24, 24],
    [776, 776],
  ],
  { type: "FeatureCollection", features: mapFeatures },
);
const pathGenerator = geoPath().projection(projection);
const usPaths = renderPaths(usStates);
const canadaPaths = renderPaths(canadaGeoJson.features);

const output = `// Generated by scripts/generate-alumni-map.mjs. Do not edit by hand.\n\nexport const US_STATE_PATHS = ${JSON.stringify(usPaths)} as const;\n\nexport const CANADA_PROVINCE_PATHS = ${JSON.stringify(canadaPaths)} as const;\n`;

await writeFile(outputPath, output);

console.log(
  `Generated ${usPaths.length + canadaPaths.length} paths (${Buffer.byteLength(output)} bytes).`,
);
